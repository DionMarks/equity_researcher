PUB = date(2026, 5, 1)


def ref(
    page: int, table_id: str | None = None, doc: str = "anz-1h26-results-document"
) -> SourceRef:
    return SourceRef(
        doc_id=doc, doc_type="RESULTS_DOCUMENT", page=page, table_id=table_id, publish_date=PUB
    )


def card(
    evidence_id: str,
    component: str,
    value: str | None,
    page: int,
    quote: str,
    period: str = "1H26",
) -> EvidenceCard:
    return EvidenceCard(
        evidence_id=evidence_id,
        component=component,
        period=period,
        value=Decimal(value) if value is not None else None,
        unit="pct" if component.endswith("headline") else "bps",
        basis=Basis(scope="level2"),
        statement=f"{component} read from a table in the results document.",
        quote=quote,
        source=ref(page, "t_capital"),
        method="table",
        checks_passed=["identity"],
    )


def confidence(level: str, score: float) -> Confidence:
    return Confidence(level=level, score=score, reasons=["base 0.92 for computed evidence"])


