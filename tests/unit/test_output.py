def test_every_view_counts_the_model_calls_the_same_way():
    """ANZ's memo said "4 model calls" under how it was answered and "2 model calls" in its
    footer: two calls were replayed from the cache, and one count left them out."""
    from bankresearch.output.render_md import model_calls_said
    from bankresearch.output.schema import ModelCall, Trail

    trail = Trail(
        model_calls=[
            ModelCall(step="text_walk", cached=True, cost_usd=Decimal(0)),
            ModelCall(step="taxonomy_classify", cached=True, cost_usd=Decimal(0)),
            ModelCall(step="explain", cost_usd=Decimal("0.140305")),
            ModelCall(step="verify", cost_usd=Decimal("0.094625")),
        ]
    )
    res = result(trail=trail)
    res.diagnostics.llm_calls = 2
    res.diagnostics.cost_usd = Decimal("0.23493")
    said = "4 model calls (2 replayed from the cache)"
    assert model_calls_said(res) == said
    memo = render_markdown(res)
    assert f"{said}, A$0.34 in all." in memo
    assert f"{said} · A$0.34" in memo


def test_result_json_carries_computed_figures_as_a_reader_would():
    """Exact arithmetic left 28 digits in result.json: 420.0000000000000000000000000000,
    0E-28. The run keeps every digit; only the JSON is rounded."""
    import json

    from bankresearch.output.schema import tidy

    assert str(tidy(Decimal("420.0000000000000000000000000000"))) == "420"
    assert str(tidy(Decimal("0E-28"))) == "0"
    assert str(tidy(Decimal("-0E-26"))) == "0"
    assert str(tidy(Decimal("50.6590019178082191780821917808"))) == "50.659"
    res = result()
    exact = res.drivers[0].contribution
    dumped = res.model_dump_json()
    assert "E-" not in dumped and "0000000000" not in dumped
    assert res.drivers[0].contribution == exact  # unchanged in memory
    assert json.loads(dumped)["reconciliation"]
