@pytest.fixture
def empty_corpus(tmp_path) -> dict[str, str]:
    """A data directory with nothing ingested, so `run` abstains without the network."""
    return {
        "BANKRESEARCH_DATA_DIR": str(tmp_path / "data"),
        "BANKRESEARCH_RUNS_DIR": str(tmp_path / "runs"),
    }


ASK = [
    "run",
    "--bank",
    "ANZ",
    "--period",
    "1H26",
    "--metric",
    "nim",
    "--as-of",
    "2026-05-31",
    "--yes",
]


def test_json_output_is_bare_json_a_script_can_parse(empty_corpus, scripted_model):
    outcome = CliRunner().invoke(app, [*ASK, "--format", "json"], env=empty_corpus)
    assert outcome.exit_code == 2, outcome.output
    payload = json.loads(outcome.stdout)
    assert payload["status"] == "ABSTAIN"
    assert payload["abstain_reason"]


def test_the_terminal_view_is_the_default(empty_corpus, scripted_model):
    outcome = CliRunner().invoke(app, ASK, env=empty_corpus)
    assert outcome.exit_code == 2, outcome.output
    assert "No answer" in outcome.stdout
    assert "What to do" in outcome.stdout
