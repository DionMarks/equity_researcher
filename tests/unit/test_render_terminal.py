def test_an_abstention_says_why_and_what_to_do_about_it():
    text = shown(abstention())
    assert "No answer" in text
    assert "DOCS_UNAVAILABLE" in text
    assert "No ingested disclosures for ANZ 1H26 or 1H25." in text
    assert "What to do" in text
    assert "make ingest" in text
    assert "Drivers explain" not in text


def test_an_answer_without_drivers_says_so_rather_than_leaving_a_gap():
    text = shown(result(status="PARTIAL", drivers=[], residual=None, reconciliation=None))
    assert "No drivers established" in text


def test_a_nested_driver_sits_beneath_its_parent():
    res = result()
    res.drivers.append(
        Driver(
            driver_id="cet1.rwa_irrbb",
            parent_id="cet1.rwa_credit",
            label="IRRBB RWA",
            contribution=Decimal("-3.1"),
            direction="-",
            method="computed",
            evidence_type="computed",
            confidence=confidence("High", 0.92),
        )
    )
    text = shown(res)
    assert text.index("Credit RWA") < text.index("↳ IRRBB RWA")


def test_the_narrative_keeps_its_citations_as_the_pages_they_point_at():
    text = shown(result())
    assert "12.39% [p.7]" in text
    assert "87.5bp [p.12]" in text
    assert "[ev_" not in text


def test_a_page_number_two_documents_share_is_cited_with_its_document():
    res = result()
    other = res.evidence[2].model_copy(
        update={
            "evidence_id": "ev_009",
            "source": res.evidence[2].source.model_copy(update={"doc_id": "anz-1h26-pillar3"}),
        }
    )
    res.evidence.append(other)
    # A card the answer never shows doesn't make its page ambiguous ...
    assert "[p.12]" in shown(res, width=200)
    # ... one it cites does.
    res.drivers[0].evidence_ids.append("ev_009")
    assert "[anz-1h26-results-document p.12]" in shown(res, width=200)


def test_caveats_beyond_eight_are_counted_rather_than_printed():
    text = shown(result(caveats=[f"note-{n:02d}" for n in range(11)]))
    assert "note-07" in text
    assert "note-08" not in text
    assert "3 more in result.json" in text


@pytest.mark.parametrize("width", [60, 80, 92, 100, 120, 160])
def test_no_terminal_width_cuts_anything_off(width: int):
    res = result()
    res.drivers[0] = res.drivers[0].model_copy(
        update={"label": "Capital generated by earnings net of the regulatory deductions"}
    )
    for line in shown(res, width=width).splitlines():
        assert len(line) <= width, line


def test_a_wide_terminal_shows_each_drivers_pages_and_a_narrow_one_still_lists_them():
    wide, narrow = shown(result(), width=160), shown(result(), width=60)

    def header(text: str) -> str:
        return next(line for line in text.splitlines() if "Contribution" in line)

    assert "Source" in header(wide)
    assert "Source" not in header(narrow)
    for page in ("p.12", "p.40"):
        assert page in narrow  # under Sources, where they are never cut


def test_a_zero_share_never_reads_as_negative():
    assert format_share(Decimal("-0.0")) == "0.0%"
    assert format_share(Decimal("-12.5")) == "-12.5%"
    assert format_share(None) == "n/a"


def test_a_driver_that_moved_nothing_draws_no_bar():
    assert _bar(Decimal(0), Decimal(10)).plain == ""
    assert _bar(Decimal("0.01"), Decimal(10)).plain == "█"


def test_every_abstention_reason_comes_with_something_to_do():
    assert set(_NEXT_STEP) == set(get_args(AbstainReason))


def test_the_advice_names_only_commands_that_exist():
    """A hint naming a command that does not exist is worse than no hint.

    One pointed at `bankresearch banks`, which was never a command.
    """
    commands = set(typer.main.get_command(app).commands)  # type: ignore[attr-defined]
    for reason, hint in _NEXT_STEP.items():
        for named in re.findall(r"`bankresearch ([a-z-]+)", hint):
            assert named in commands, f"{reason} names `bankresearch {named}`"


