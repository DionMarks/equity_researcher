class Uncropped(Console):
    """Shows what overflows the terminal instead of cutting it off at the edge.

    A normal console crops every line to its width, so a check that no line is too long
    passes whether or not the layout fits. That's how a table that cut "p.22" down to "p.2"
    got through.
    """

    def print(self, *objects, **kwargs):  # type: ignore[no-untyped-def,override]
        kwargs["crop"] = False
        super().print(*objects, **kwargs)


def shown(res: ResearchResult, width: int = 120) -> str:
    console = Uncropped(file=io.StringIO(), width=width, color_system=None)
    render_terminal(res, console, artefacts="runs/example")
    assert isinstance(console.file, io.StringIO)
    return console.file.getvalue()


def abstention() -> ResearchResult:
    return result(
        status="ABSTAIN",
        abstain_reason="DOCS_UNAVAILABLE",
        current=None,
        prior=None,
        change=None,
        drivers=[],
        residual=None,
        reconciliation=None,
        overall_confidence=None,
        narrative="",
        caveats=["No ingested disclosures for ANZ 1H26 or 1H25."],
    )


def test_an_answer_leads_with_its_status_bank_metric_and_periods():
    text = shown(result())
    header = text[: text.index("Drivers")]
    for expected in ("OK", "ANZ Group Holdings Limited", "CET1 ratio", "1H26", "1H25"):
        assert expected in header


def test_the_movement_shows_both_figures_the_change_and_its_confidence():
    text = shown(result())
    assert "12.21%" in text
    assert "12.39%" in text
    assert "+18.0 bps" in text
    assert "Figure confidence" in text


def test_drivers_are_listed_largest_first():
    text = shown(result())
    order = [
        text.index("Capital generated by earnings"),
        text.index("Dividends net of DRP"),
        text.index("Credit RWA"),
    ]
    assert order == sorted(order)


def test_the_reconciliation_states_the_arithmetic_and_whether_it_closes():
    text = shown(result())
    assert "Drivers explain" in text
    assert "residual" in text
    assert "✗" in text  # the fixture's residual is outside tolerance
